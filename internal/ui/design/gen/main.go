// Command gen writes internal/ui/design/tokens_gen.go from the coss ui spec
// in docs/design/coss/tokens.json. Run it through go generate in
// internal/ui/design; the output is committed so builds never read the JSON.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type colorEntry struct {
	Hex string `json:"hex"`
	CSS string `json:"css"`
}

type tokens struct {
	Meta struct {
		Commit string `json:"commit"`
	} `json:"meta"`
	Palette  map[string]colorEntry `json:"palette"`
	Semantic struct {
		Light map[string]colorEntry `json:"light"`
		Dark  map[string]colorEntry `json:"dark"`
	} `json:"semantic"`
	Radius     map[string]json.RawMessage `json:"radius"`
	Typography struct {
		Scale map[string]struct {
			FontSize   string `json:"fontSize"`
			LineHeight string `json:"lineHeight"`
		} `json:"scale"`
		Weights  map[string]int     `json:"weights"`
		Tracking map[string]string  `json:"tracking"`
		Leading  map[string]float64 `json:"leading"`
	} `json:"typography"`
	Shadows struct {
		Scale map[string]struct {
			Resolved string `json:"resolved"`
		} `json:"scale"`
	} `json:"shadows"`
	Motion struct {
		Defaults struct {
			Duration string `json:"duration"`
			Easing   string `json:"easing"`
		} `json:"defaults"`
		Easings         map[string]string   `json:"easings"`
		TransitionsUsed map[string][]string `json:"transitionsUsed"`
		EnterExit       []struct {
			Part   string                     `json:"part"`
			Target string                     `json:"target"`
			State  string                     `json:"state"`
			Props  map[string]json.RawMessage `json:"props"`
		} `json:"enterExit"`
	} `json:"motion"`
}

func main() {
	in := flag.String("in", "../../../docs/design/coss/tokens.json", "tokens.json")
	out := flag.String("out", "tokens_gen.go", "output Go file")
	flag.Parse()
	raw, err := os.ReadFile(*in)
	if err != nil {
		log.Fatal(err)
	}
	var t tokens
	if err := json.Unmarshal(raw, &t); err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("// Code generated by internal/ui/design/gen from docs/design/coss/tokens.json; DO NOT EDIT.\n\n")
	w("package design\n\nimport (\n\t\"time\"\n\n\t\"github.com/egoist/mygo/ui\"\n)\n\n")
	w("// SpecCommit is the cosscom/ui commit the tokens were extracted from.\nconst SpecCommit = %q\n\n", t.Meta.Commit)

	// Semantic palette.
	order := semanticOrder(sortedKeys(t.Semantic.Light))
	w("// Palette holds the coss semantic color tokens of one scheme. Translucent\n// tokens keep their alpha: composite them over what is underneath.\ntype Palette struct {\n")
	for _, k := range order {
		w("\t%s ui.Color // --%s\n", camel(k), k)
	}
	w("}\n\n")
	for _, mode := range []struct {
		name string
		m    map[string]colorEntry
	}{{"cossLight", t.Semantic.Light}, {"cossDark", t.Semantic.Dark}} {
		w("var %s = Palette{\n", mode.name)
		for _, k := range order {
			w("\t%s: %s, // %s\n", camel(k), colorLit(mode.m[k].Hex), mode.m[k].Hex)
		}
		w("}\n\n")
	}

	// Tailwind palette.
	pk := sortedKeys(t.Palette)
	sort.SliceStable(pk, func(i, j int) bool { return paletteLess(pk[i], pk[j]) })
	w("// Swatches is the Tailwind v4 palette coss draws on (sRGB, clipped).\ntype Swatches struct {\n")
	for _, k := range pk {
		w("\t%s ui.Color\n", camel(k))
	}
	w("}\n\n// TW is the Tailwind palette.\nvar TW = Swatches{\n")
	for _, k := range pk {
		w("\t%s: %s,\n", camel(k), colorLit(t.Palette[k].Hex))
	}
	w("}\n\n")

	// Radius.
	w("// Radius scale in DIPs (rounded-*).\nconst (\n")
	for _, k := range []string{"xs", "sm", "md", "lg", "xl", "2xl", "3xl", "4xl"} {
		var e struct {
			PX string `json:"px"`
		}
		if err := json.Unmarshal(t.Radius[k], &e); err != nil {
			log.Fatalf("radius %s: %v", k, err)
		}
		w("\tRadius%s float32 = %s\n", scaleName(k), num(px(e.PX)))
	}
	w("\tRadiusFull float32 = 9999\n)\n\n")

	// Typography.
	w("// Type scale (text-*): size and line height in DIPs.\nvar (\n")
	for _, k := range []string{"xs", "sm", "base", "lg", "xl", "2xl", "3xl", "4xl", "5xl"} {
		s := t.Typography.Scale[k]
		w("\tText%s = TextStyle{Size: %s, LineHeight: %s}\n", scaleName(k), num(px(s.FontSize)), num(round2(px(s.LineHeight))))
	}
	w(")\n\n// Font weights.\nconst (\n")
	for _, k := range []string{"normal", "medium", "semibold", "bold"} {
		w("\tWeight%s = %d\n", camel(k), t.Typography.Weights[k])
	}
	w(")\n\n// Letter spacing in em (tracking-*).\nconst (\n")
	for _, k := range []string{"tighter", "tight", "normal", "wide", "wider", "widest"} {
		w("\tTracking%s float32 = %s\n", camel(k), num(em(t.Typography.Tracking[k])))
	}
	w(")\n\n")

	// Shadows.
	w("// Shadow scale (shadow-*, inset-shadow-*, drop-shadow-*), black at the\n// scale's own alpha; Shadows.Tint re-tints a scale for the alpha modifier.\nvar (\n")
	for _, k := range sortedKeys(t.Shadows.Scale) {
		if strings.Contains(k, "/") {
			continue
		}
		w("\t%s = %s\n", camel(k), shadowLit(t.Shadows.Scale[k].Resolved))
	}
	w(")\n\n")

	// Motion.
	w("// DurationDefault is Tailwind's transition-* default duration.\nconst DurationDefault = %s\n\n", dur(t.Motion.Defaults.Duration))
	w("// Easings (ease-*), plus the curves coss writes inline.\nvar (\n")
	for _, k := range sortedKeys(t.Motion.Easings) {
		v := t.Motion.Easings[k]
		if v == "linear" {
			w("\tCurve%s = CubicBezier{0, 0, 1, 1}\n", camel(k))
			continue
		}
		w("\tCurve%s = %s\n", camel(k), bezierLit(v))
	}
	w("\tCurveDrawer = CubicBezier{0.32, 0.72, 0, 1}\n")
	w("\tCurveToastSlide = CubicBezier{0.22, 1, 0.36, 1}\n")
	w(")\n\n")

	// Transitions per part.
	type tr struct {
		part, props, d, curve string
	}
	var trs []tr
	reT := regexp.MustCompile(`^(.*) · (\d+)ms · (.*)$`)
	for k, parts := range t.Motion.TransitionsUsed {
		m := reT.FindStringSubmatch(k)
		if m == nil {
			continue // raw transition/animation shorthands: hand-mapped in motion.go
		}
		curve := m[3]
		if curve == "linear" {
			curve = "CubicBezier{0, 0, 1, 1}"
		} else {
			curve = bezierLit(curve)
		}
		for _, p := range parts {
			trs = append(trs, tr{p, m[1], m[2] + " * time.Millisecond", curve})
		}
	}
	sort.Slice(trs, func(i, j int) bool {
		if trs[i].part != trs[j].part {
			return trs[i].part < trs[j].part
		}
		return trs[i].props < trs[j].props
	})
	w("// transitions maps a coss part (component/slot[config]) to its transition.\nvar transitions = map[string]Transition{\n")
	seen := map[string]bool{}
	for _, x := range trs {
		if seen[x.part] {
			continue
		}
		seen[x.part] = true
		w("\t%q: {Props: %q, Duration: %s, Curve: %s},\n", x.part, x.props, x.d, x.curve)
	}
	w("}\n\n")

	// Enter/exit deltas.
	w("// deltas maps \"part|enter\" or \"part|exit\" to what the part animates from\n// on open (data-starting-style) or to on close (data-ending-style).\nvar deltas = map[string]Delta{\n")
	type dl struct {
		key string
		d   string
	}
	var dls []dl
	dseen := map[string]bool{}
	for _, e := range t.Motion.EnterExit {
		if e.Target != "self" {
			continue
		}
		phase := "enter"
		if strings.HasPrefix(e.State, "ending") {
			phase = "exit"
		} else if !strings.HasPrefix(e.State, "starting") {
			continue
		}
		key := e.Part + "|" + phase
		if dseen[key] {
			continue
		}
		dseen[key] = true
		dls = append(dls, dl{key, deltaLit(e.Props)})
	}
	sort.Slice(dls, func(i, j int) bool { return dls[i].key < dls[j].key })
	for _, x := range dls {
		w("\t%q: %s,\n", x.key, x.d)
	}
	w("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func sortedKeys[V any](m map[string]V) []string {
	k := make([]string, 0, len(m))
	for s := range m {
		k = append(k, s)
	}
	sort.Strings(k)
	return k
}

// semanticOrder keeps a token next to its foreground, in the spec's order.
func semanticOrder(keys []string) []string {
	pref := []string{"background", "foreground", "card", "card-foreground", "popover", "popover-foreground",
		"primary", "primary-foreground", "secondary", "secondary-foreground", "muted", "muted-foreground",
		"accent", "accent-foreground", "destructive", "destructive-foreground", "info", "info-foreground",
		"success", "success-foreground", "warning", "warning-foreground", "border", "input", "ring",
		"chart-1", "chart-2", "chart-3", "chart-4", "chart-5", "sidebar", "sidebar-foreground",
		"sidebar-primary", "sidebar-primary-foreground", "sidebar-accent", "sidebar-accent-foreground",
		"sidebar-border", "sidebar-ring", "code", "code-foreground", "code-highlight"}
	have := map[string]bool{}
	for _, k := range keys {
		have[k] = true
	}
	var out []string
	for _, k := range pref {
		if have[k] {
			out = append(out, k)
			delete(have, k)
		}
	}
	for _, k := range keys {
		if have[k] {
			out = append(out, k)
		}
	}
	return out
}

var hues = []string{"red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue", "indigo", "violet", "purple", "fuchsia", "pink", "rose", "slate", "gray", "zinc", "neutral", "stone", "black", "white"}

func paletteLess(a, b string) bool {
	ha, sa := splitSwatch(a)
	hb, sb := splitSwatch(b)
	if ha != hb {
		return ha < hb
	}
	return sa < sb
}

func splitSwatch(s string) (int, int) {
	name, step, _ := strings.Cut(s, "-")
	h := len(hues)
	for i, x := range hues {
		if x == name {
			h = i
		}
	}
	n, _ := strconv.Atoi(step)
	return h, n
}

func camel(s string) string {
	var b strings.Builder
	up := true
	for _, r := range s {
		if r == '-' || r == '/' || r == '_' {
			up = true
			continue
		}
		if up && r >= 'a' && r <= 'z' {
			r -= 'a' - 'A'
		}
		up = false
		b.WriteRune(r)
	}
	return b.String()
}

func scaleName(k string) string {
	switch k {
	case "2xl":
		return "XL2"
	case "3xl":
		return "XL3"
	case "4xl":
		return "XL4"
	case "5xl":
		return "XL5"
	case "xs", "sm", "md", "lg", "xl":
		return strings.ToUpper(k)
	}
	return camel(k)
}

func colorLit(hex string) string {
	h := strings.TrimPrefix(hex, "#")
	if len(h) == 6 {
		h += "ff"
	}
	if len(h) != 8 {
		log.Fatalf("bad color %q", hex)
	}
	v, err := strconv.ParseUint(h, 16, 32)
	if err != nil {
		log.Fatalf("bad color %q", hex)
	}
	return fmt.Sprintf("ui.Color{R: %d, G: %d, B: %d, A: %d}", v>>24, v>>16&0xff, v>>8&0xff, v&0xff)
}

func px(s string) float64 {
	s = strings.Fields(strings.TrimSpace(s))[0]
	f, err := strconv.ParseFloat(strings.TrimSuffix(s, "px"), 64)
	if err != nil {
		log.Fatalf("bad px %q", s)
	}
	return f
}

func em(s string) float64 {
	f, err := strconv.ParseFloat(strings.TrimSuffix(s, "em"), 64)
	if err != nil {
		log.Fatalf("bad em %q", s)
	}
	return f
}

func round2(f float64) float64 { return math.Round(f*100) / 100 }

func num(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

func dur(s string) string { return strings.TrimSuffix(s, "ms") + " * time.Millisecond" }

var reBezier = regexp.MustCompile(`cubic-bezier\(\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*,\s*([-\d.]+)\s*\)`)

func bezierLit(s string) string {
	m := reBezier.FindStringSubmatch(s)
	if m == nil {
		log.Fatalf("bad bezier %q", s)
	}
	return fmt.Sprintf("CubicBezier{%s, %s, %s, %s}", m[1], m[2], m[3], m[4])
}

// shadowLit turns "0 1px 3px 0 #0000001a, inset 0 1px #..." into a Shadows
// literal.
func shadowLit(s string) string {
	var parts []string
	for _, layer := range strings.Split(s, ",") {
		f := strings.Fields(strings.TrimSpace(layer))
		inset := false
		if len(f) > 0 && f[0] == "inset" {
			inset, f = true, f[1:]
		}
		color := f[len(f)-1]
		vals := [4]float64{}
		for i, n := range f[:len(f)-1] {
			vals[i] = px(n)
		}
		parts = append(parts, fmt.Sprintf("{X: %s, Y: %s, Blur: %s, Spread: %s, Color: %s, Inset: %v}",
			num(vals[0]), num(vals[1]), num(vals[2]), num(vals[3]), colorLit(color), inset))
	}
	return "Shadows{" + strings.Join(parts, ", ") + "}"
}

var (
	reTranslate = regexp.MustCompile(`^(-?[\d.]+)(px)?\s+(-?[\d.]+)(px)?$`)
	// reSlide reads translateX/Y(calc(±100% ± [env(...) +] Npx)): a slide by
	// the element's own size plus an offset.
	reSlide = regexp.MustCompile(`^translate([XY])\(calc\((-?)100% ([+-]) (?:env\([^)]*\) \+ )?(\d+)px\)\)$`)
)

func deltaLit(props map[string]json.RawMessage) string {
	var fields, raw []string
	for _, k := range sortedKeys(props) {
		var v string
		if err := json.Unmarshal(props[k], &v); err != nil {
			continue // structured values (per-scheme colors) stay symbolic
		}
		switch k {
		case "opacity":
			f, _ := strconv.ParseFloat(strings.TrimSuffix(v, "%"), 64)
			fields = append(fields, "Opacity: "+num(f/100), "HasOpacity: true")
		case "scale":
			f, _ := strconv.ParseFloat(strings.TrimSuffix(strings.Fields(v)[0], "%"), 64)
			fields = append(fields, "Scale: "+num(f/100))
		case "translate":
			if m := reTranslate.FindStringSubmatch(v); m != nil {
				x, _ := strconv.ParseFloat(m[1], 64)
				y, _ := strconv.ParseFloat(m[3], 64)
				fields = append(fields, "TranslateX: "+num(x), "TranslateY: "+num(y))
			} else {
				raw = append(raw, k+": "+v)
			}
		case "transform":
			if m := reSlide.FindStringSubmatch(v); m != nil {
				sign := 1.0
				if m[2] == "-" {
					sign = -1
				}
				off, _ := strconv.ParseFloat(m[4], 64)
				if m[3] == "-" {
					off = -off
				}
				if m[1] == "X" {
					fields = append(fields, "SlideX: "+num(sign), "TranslateX: "+num(off))
				} else {
					fields = append(fields, "SlideY: "+num(sign), "TranslateY: "+num(off))
				}
			} else {
				raw = append(raw, k+": "+v)
			}
		case "height":
			if v == "0px" {
				fields = append(fields, "Collapse: true")
			} else {
				raw = append(raw, k+": "+v)
			}
		default:
			raw = append(raw, k+": "+v)
		}
	}
	if len(raw) > 0 {
		fields = append(fields, fmt.Sprintf("Raw: %q", strings.Join(raw, "; ")))
	}
	return "{" + strings.Join(fields, ", ") + "}"
}
