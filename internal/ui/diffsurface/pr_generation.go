package diffsurface

import (
	"context"
	"github.com/egoist/mygo/ui"
	"time"
	"whaleisle/internal/desktop/git"
	fonttheme "whaleisle/internal/ui/theme"
)

type prGenerationTask struct {
	root   string
	cancel context.CancelFunc
	done   chan prGenerated
}
type prGenerated struct {
	content git.GeneratedPRContent
	err     error
}

func (w *Workbench) cancelPRGeneration() {
	if w.Remote != nil && w.Remote.Generation != nil {
		w.Remote.Generation.cancel()
		w.Remote.Generation = nil
		if w.Progress != nil {
			w.Progress.Finish(word("生成已取消，保留手写内容", "Generation canceled; your text is preserved"), false)
		}
	}
}
func beginPRGeneration(c *ui.Context, m Model) {
	if !captionAdmitted(m) {
		return
	}
	w := m.Workbench
	s := w.Remote
	if s == nil || s.Generation != nil || s.Task != nil || w.Operation != nil {
		return
	}
	root := m.WorkspaceRoot
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	task := &prGenerationTask{root: root, cancel: cancel, done: make(chan prGenerated, 1)}
	s.Generation = task
	s.Generated = nil
	s.GenerationError = ""
	s.Plan = nil
	s.PR = nil
	invalidate := c.Services().Invalidate
	progress := git.NewProgress(root, word("正在生成 PR 标题和正文…", "Generating PR title and body…"), invalidate)
	w.Progress = progress
	ctx = git.WithProgress(ctx, progress)
	go func() {
		result, e := git.GeneratePullRequestContent(ctx, root)
		phase := word("PR 文案已生成，等待采用和核对", "PR copy generated; apply and review it")
		if e != nil {
			phase = word("生成失败，手写内容已保留", "Generation failed; your text is preserved")
		}
		progress.Finish(phase, e != nil)
		task.done <- prGenerated{content: result, err: e}
		if invalidate != nil {
			invalidate()
		}
	}()
}
func finishPRGeneration(m Model) {
	w := m.Workbench
	s := w.Remote
	if s == nil || s.Generation == nil {
		return
	}
	task := s.Generation
	if task.root != m.WorkspaceRoot {
		w.cancelPRGeneration()
		return
	}
	select {
	case result := <-task.done:
		task.cancel()
		s.Generation = nil
		if result.err != nil {
			s.GenerationError = result.err.Error()
			return
		}
		s.Generated = &result.content
	default:
	}
}
func (w *Workbench) applyGeneratedPR() {
	s := w.Remote
	if s == nil || s.Generated == nil {
		return
	}
	s.Title, s.Body = s.Generated.Title, s.Generated.Body
	s.Plan = nil
	s.PR = nil
	s.Generated = nil
	s.GenerationError = ""
}
func paintPRGeneration(c *ui.Context, m Model, fg, muted ui.Color) {
	w := m.Workbench
	finishPRGeneration(m)
	s := w.Remote
	if s == nil {
		return
	}
	ui.Text(c, word("生成会向已配置模型发送此分支已提交的 diff、提交列表和目标分支模板；没有 API key 时按提交历史生成。", "Generation sends this branch's committed diff, commit list and base template to the configured model. Without an API key it uses local commit history.")).FontSize(fonttheme.InterfaceSize(10)).TextColor(muted)
	if s.Generation != nil {
		ui.Text(c, word("正在生成；可继续手写，结果不会覆盖当前内容。", "Generating; you can keep editing. Results will not overwrite your text.")).FontSize(fonttheme.InterfaceSize(10)).TextColor(fg)
		if ui.Button(c, word("取消生成", "Cancel generation")).Clicked() {
			w.cancelPRGeneration()
		}
	} else if ui.Button(c, word("自动生成 PR 标题和正文", "Generate PR title and body")).Disabled(s.Task != nil).Clicked() {
		beginPRGeneration(c, m)
	}
	if s.GenerationError != "" {
		ui.Text(c, s.GenerationError).FontSize(fonttheme.InterfaceSize(11)).TextColor(fg)
	}
	if g := s.Generated; g != nil {
		label := word("根据提交历史生成（未配置 API key）", "Generated from commit history (no API key configured)")
		if g.Source == "model" {
			label = word("由已配置模型生成", "Generated by the configured model")
		}
		ui.Text(c, label).FontSize(fonttheme.InterfaceSize(10)).TextColor(muted)
		ui.Text(c, g.Repository+" · "+g.Base+" ← "+g.Head).FontSize(fonttheme.InterfaceSize(10)).TextColor(muted)
		ui.Text(c, g.Title).FontSize(fonttheme.InterfaceSize(11)).TextColor(fg)
		ui.Text(c, g.Body).FontSize(fonttheme.InterfaceSize(10)).TextColor(fg)
		ui.Text(c, word("采用会替换上方标题和正文；发布仍需重新核对并确认。", "Apply replaces the title and body above. Publishing still requires review and confirmation.")).FontSize(fonttheme.InterfaceSize(10)).TextColor(muted)
		ui.Row(c).Gap(6).Children(func() {
			if ui.Button(c, word("采用生成文案", "Use generated copy")).Clicked() {
				w.applyGeneratedPR()
			}
			if ui.Button(c, word("保留手写内容", "Keep my text")).Clicked() {
				s.Generated = nil
			}
		})
	}
}
