// AgentsParityFormat 取词并将 {name} 形式占位符替换为成对给出的键值。
func AgentsParityFormat(key string, kv ...string) string {
	text := T(key)
	for i := 0; i+1 < len(kv); i += 2 {
		text = strings.ReplaceAll(text, "{"+kv[i]+"}", kv[i+1])
	}
	return text
}

