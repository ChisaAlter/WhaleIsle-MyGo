package main

import (
	"fmt"
	"go/format"
	"path/filepath"
	"strconv"
	"strings"
)

type rootEmit struct {
	root     PersistenceRoot
	goName   string
	defs     []string
	needJSON bool
}

func renderEventsPackage(inv *Inventory, srcPath, pkgName string) ([]byte, error) {
	var emits []rootEmit
	used := map[string]bool{}
	for _, r := range inv.Roots {
		base := rootGoName(r)
		name := base
		for i := 2; used[name]; i++ {
			name = base + strconv.Itoa(i)
		}
		used[name] = true

		doc := fmt.Sprintf("the wire type of persistence root %s (%s)", r.Key, r.Kind)
		if r.Kind == "event" {
			doc = fmt.Sprintf("the wire type of session event %q", r.Event)
			if r.Surface {
				doc += " (surface)"
			}
		}
		m := newTypeMapper(r.Schema.Nodes, name, doc)
		// Seed sibling root names so nested types cannot collide with them.
		for n := range used {
			if n != name {
				m.used[n] = true
			}
		}
		goName, err := m.declareRoot(r.Schema.Root, name)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", r.Key, err)
		}
		// Also reserve every nested named type declared for this root.
		for n := range m.used {
			used[n] = true
		}
		emits = append(emits, rootEmit{
			root:     r,
			goName:   goName,
			defs:     m.defs,
			needJSON: m.needJSON,
		})
	}

	needJSON := true // Envelope always uses json.RawMessage

	var head, body strings.Builder
	fmt.Fprintf(&head, "// Code generated by tools/gen-events %s from %s; DO NOT EDIT.\n", genVersion, filepath.ToSlash(srcPath))
	head.WriteString("//\n")
	fmt.Fprintf(&head, "// Persistence schema formatVersion %d; %d roots.\n\n", inv.FormatVersion, len(inv.Roots))
	fmt.Fprintf(&head, "package %s\n\n", pkgName)
	if needJSON {
		head.WriteString("import \"encoding/json\"\n\n")
	}

	body.WriteString(`// Kind classifies a persistence root vocabulary.
type Kind string

const (
	KindHeader   Kind = "header"
	KindEnvelope Kind = "envelope"
	KindEvent    Kind = "event"
)

`)

	// Event type string constants.
	body.WriteString("// Session event type strings (root.event values).\n")
	body.WriteString("const (\n")
	for _, e := range emits {
		if e.root.Kind != "event" {
			continue
		}
		constName := "Type" + e.goName
		fmt.Fprintf(&body, "\t%s = %s\n", constName, strconv.Quote(e.root.Event))
	}
	body.WriteString(")\n\n")

	body.WriteString(`// Envelope is a best-effort common shape shared by session events.
// Typed event structs below embed the same JSON keys; use Envelope when the
// concrete type is not yet known, then unmarshal again into the matching type.
type Envelope struct {
	Type            string          ` + "`json:\"type\"`" + `
	Seq             float64         ` + "`json:\"seq\"`" + `
	Time            float64         ` + "`json:\"time\"`" + `
	Data            json.RawMessage ` + "`json:\"data\"`" + `
	Ignorable       *bool           ` + "`json:\"ignorable,omitempty\"`" + `
	SurfaceOp       json.RawMessage ` + "`json:\"surfaceOp,omitempty\"`" + `
	SourceEventSeqs []float64       ` + "`json:\"sourceEventSeqs,omitempty\"`" + `
}

`)

	body.WriteString(`// RootInfo describes one persistence root from the schema inventory.
type RootInfo struct {
	Key     string // inventory key (e.g. "event:user/message")
	Kind    Kind
	Event   string // set when Kind is KindEvent
	Surface bool
	Digest  string
	GoType  string // generated Go type name
}

`)

	body.WriteString("// Roots lists every persistence root in inventory order.\n")
	body.WriteString("var Roots = []RootInfo{\n")
	for _, e := range emits {
		fmt.Fprintf(&body, "\t{Key: %s, Kind: %s, Event: %s, Surface: %v, Digest: %s, GoType: %s},\n",
			strconv.Quote(e.root.Key),
			kindConst(e.root.Kind),
			strconv.Quote(e.root.Event),
			e.root.Surface,
			strconv.Quote(e.root.Digest),
			strconv.Quote(e.goName),
		)
	}
	body.WriteString("}\n\n")

	body.WriteString("// EventsByType maps session event type strings to their RootInfo.\n")
	body.WriteString("var EventsByType = map[string]RootInfo{\n")
	for _, e := range emits {
		if e.root.Kind != "event" {
			continue
		}
		fmt.Fprintf(&body, "\t%s: {Key: %s, Kind: KindEvent, Event: %s, Surface: %v, Digest: %s, GoType: %s},\n",
			strconv.Quote(e.root.Event),
			strconv.Quote(e.root.Key),
			strconv.Quote(e.root.Event),
			e.root.Surface,
			strconv.Quote(e.root.Digest),
			strconv.Quote(e.goName),
		)
	}
	body.WriteString("}\n\n")

	for _, e := range emits {
		for _, def := range e.defs {
			body.WriteString(def)
			if !strings.HasSuffix(def, "\n") {
				body.WriteByte('\n')
			}
			body.WriteByte('\n')
		}
	}

	src := head.String() + body.String()
	formatted, err := format.Source([]byte(src))
	if err != nil {
		return nil, fmt.Errorf("generated Go does not parse: %w\n--- raw output ---\n%s", err, src)
	}
	return formatted, nil
}

func kindConst(kind string) string {
	switch kind {
	case "header":
		return "KindHeader"
	case "envelope":
		return "KindEnvelope"
	case "event":
		return "KindEvent"
	default:
		return strconv.Quote(kind)
	}
}
