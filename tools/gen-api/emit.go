package main

import (
	"fmt"
	"path/filepath"
	"strconv"
	"strings"

	"go/format"
)

type genPackage struct {
	root       string
	srcPath    string
	parsed     *parsedFile
	tf         *typertFile
	goName     string // e.g. dsh_llm (file name base and idempotency key)
	prefix     string // e.g. DshLlm (exported identifier prefix)
	shortName  string // e.g. dsh-llm
	rendered   []byte
}

// goPackageNames derives the sanitized Go name base and exported prefix for
// a typert package name (e.g. "@deepseek-ai/dsh-llm" -> "dsh_llm", "DshLlm").
func goPackageNames(pkgField, dirBase string) (string, string) {
	name := pkgField
	if i := strings.LastIndex(name, "/"); i >= 0 {
		name = name[i+1:]
	}
	name = sanitizeLower(name)
	if name == "" {
		name = sanitizeLower(dirBase)
	}
	if name == "" {
		name = "pkg"
	}
	if name[0] >= '0' && name[0] <= '9' {
		name = "p" + name
	}
	var b strings.Builder
	upper := true
	for _, r := range name {
		if r == '_' {
			upper = true
			continue
		}
		if upper {
			b.WriteRune(toUpperASCII(r))
			upper = false
		} else {
			b.WriteRune(r)
		}
	}
	return name, b.String()
}

func sanitizeLower(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	return strings.Trim(b.String(), "_")
}

func toUpperASCII(r rune) rune {
	if r >= 'a' && r <= 'z' {
		return r - 'a' + 'A'
	}
	return r
}

// describe builds the "what" phrase used in doc comments of declared types.
func describe(kind, argName, fullName, typeSymbol string) string {
	var s string
	switch kind {
	case "param":
		s = fmt.Sprintf("parameter %q of %s", argName, fullName)
	case "result":
		s = fmt.Sprintf("result of %s", fullName)
	case "uplink":
		s = fmt.Sprintf("uplink item of %s", fullName)
	default:
		s = fullName
	}
	if typeSymbol != "" {
		s += " (" + typeSymbol + ")"
	}
	return s
}

// renderPackageFile renders one per-package generated Go file. Type
// declarations collected in g are rendered together with the endpoint table.
func renderPackageFile(p *genPackage, g *goTypeer, pkgName string) ([]byte, error) {
	g.schemas = p.parsed.schemas
	g.curPkg = p.goName
	var head, b strings.Builder
	fmt.Fprintf(&head, "// Code generated by tools/gen-api %s from %s; DO NOT EDIT.\n", genVersion, filepath.ToSlash(p.srcPath))
	head.WriteString("//\n")
	fmt.Fprintf(&head, "// Source package: %s\n\n", p.tf.Package)
	fmt.Fprintf(&head, "package %s\n", pkgName)

	// Declare wire types for every parameter, result and uplink codec.
	for _, e := range p.tf.Descriptors {
		for i := range e.Params {
			prm := &e.Params[i]
			hint := nameFromSymbol(prm.TypeSymbol, e.Method, prm.Name, false)
			what := describe("param", prm.Name, e.FullName, prm.TypeSymbol)
			if _, err := g.rootType(prm.SchemaRef, prm.TypeSymbol, what, hint); err != nil {
				return nil, fmt.Errorf("%s: parameter %q: %w", e.FullName, prm.Name, err)
			}
		}
		hint := nameFromSymbol(e.ResultTypeSymbol, e.Method, "", true)
		what := describe("result", "", e.FullName, e.ResultTypeSymbol)
		if _, err := g.rootType(e.ResultSchemaRef, e.ResultTypeSymbol, what, hint); err != nil {
			return nil, fmt.Errorf("%s: result: %w", e.FullName, err)
		}
		if e.HasUplink {
			hint := nameFromSymbol(e.UplinkTypeSymbol, e.Method, "", false)
			what := describe("uplink", "", e.FullName, e.UplinkTypeSymbol)
			if _, err := g.rootType(e.UplinkSchemaRef, e.UplinkTypeSymbol, what, hint); err != nil {
				return nil, fmt.Errorf("%s: uplink: %w", e.FullName, err)
			}
		}
	}

	// Named type declarations gathered while walking the endpoints.
	for _, d := range g.defs {
		if d.pkg == p.goName {
			b.WriteString(d.code)
			b.WriteByte('\n')
		}
	}

	// Per-package descriptor table.
	fmt.Fprintf(&b, "// %sEndpoints lists the remote endpoints of %s.\n", p.prefix, p.tf.Package)
	fmt.Fprintf(&b, "var %sEndpoints = []Endpoint{\n", p.prefix)
	for _, e := range p.tf.Descriptors {
		b.WriteString(renderEndpointValue(e, p.shortName, "\t"))
		b.WriteByte('\n')
	}
	b.WriteString("}\n")

	// Raw JSON fallbacks need encoding/json.
	if strings.Contains(b.String(), "json.RawMessage") {
		head.WriteString("\nimport \"encoding/json\"\n")
	}
	head.WriteString("\n")
	head.WriteString(b.String())

	src, err := format.Source([]byte(head.String()))
	if err != nil {
		return nil, fmt.Errorf("generated Go for %s does not parse: %w", p.tf.Package, err)
	}
	return src, nil
}

// renderEndpointValue renders one composite literal for an Endpoint value at
// the given indentation.
func renderEndpointValue(e *endpointDesc, pkgShort, indent string) string {
	q := strconv.Quote
	var b strings.Builder
	b.WriteString(indent + "{\n")
	fmt.Fprintf(&b, "%s\tPackage: %s,\n", indent, q(pkgShort))
	if e.ID != "" {
		fmt.Fprintf(&b, "%s\tID: %s,\n", indent, q(e.ID))
	}
	fmt.Fprintf(&b, "%s\tMethod: %s,\n", indent, q(e.FullName))
	mode := "ModeDirect"
	if e.Stream {
		mode = "ModeStream"
	}
	fmt.Fprintf(&b, "%s\tMode: %s,\n", indent, mode)
	kind := "KindDirect"
	if e.Kind == "context" {
		kind = "KindContext"
	}
	fmt.Fprintf(&b, "%s\tKind: %s,\n", indent, kind)
	if e.Kind == "context" {
		fmt.Fprintf(&b, "%s\tContext: %s,\n", indent, q(e.Context))
		fmt.Fprintf(&b, "%s\tContextWire: %s,\n", indent, q(e.ContextWire))
	}
	if e.ScopeContext != "" {
		fmt.Fprintf(&b, "%s\tScopeContext: %s,\n", indent, q(e.ScopeContext))
		fmt.Fprintf(&b, "%s\tScopeWire: %s,\n", indent, q(e.ScopeWire))
	}
	if e.Cancellation != "" {
		fmt.Fprintf(&b, "%s\tCancellation: %s,\n", indent, q(e.Cancellation))
	}
	if len(e.Params) > 0 {
		fmt.Fprintf(&b, "%s\tParams: []Param{\n", indent)
		for _, prm := range e.Params {
			b.WriteString(indent + "\t\t{\n")
			fmt.Fprintf(&b, "%s\t\t\tName: %s,\n", indent, q(prm.Name))
			fmt.Fprintf(&b, "%s\t\t\tWire: %s,\n", indent, q(prm.Wire))
			src := "SourceJSON"
			if prm.Source == "lookup" {
				src = "SourceLookup"
			}
			fmt.Fprintf(&b, "%s\t\t\tSource: %s,\n", indent, src)
			if prm.Lookup != "" {
				fmt.Fprintf(&b, "%s\t\t\tLookup: %s,\n", indent, q(prm.Lookup))
			}
			if prm.AcceptsUndefined {
				fmt.Fprintf(&b, "%s\t\t\tOptional: true,\n", indent)
			}
			if prm.TypeSymbol != "" {
				fmt.Fprintf(&b, "%s\t\t\tTypeSymbol: %s,\n", indent, q(prm.TypeSymbol))
			}
			b.WriteString(indent + "\t\t},\n")
		}
		fmt.Fprintf(&b, "%s\t},\n", indent)
	}
	if e.UplinkTypeSymbol != "" {
		fmt.Fprintf(&b, "%s\tUplinkTypeSymbol: %s,\n", indent, q(e.UplinkTypeSymbol))
	}
	if e.ResultTypeSymbol != "" {
		fmt.Fprintf(&b, "%s\tResultTypeSymbol: %s,\n", indent, q(e.ResultTypeSymbol))
	}
	b.WriteString(indent + "},")
	return b.String()
}

// renderRegistry renders the aggregated registry file with shared types.
func renderRegistry(pkgs []*genPackage, pkgName string) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/gen-api %s; DO NOT EDIT.\n", genVersion)
	b.WriteString("//\n")
	b.WriteString("// Aggregated descriptor registry for the dsh remote API.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkgName)

	b.WriteString(`// Mode selects how an endpoint is transported.
type Mode string

const (
	ModeDirect Mode = "direct"
	ModeStream Mode = "stream"
)

// Kind selects the receiver style of an endpoint.
type Kind string

const (
	KindDirect  Kind = "direct"
	KindContext Kind = "context"
)

// Source selects how a parameter value is produced on the client.
type Source string

const (
	SourceJSON   Source = "json"
	SourceLookup Source = "lookup"
)

// Param describes one business parameter of an endpoint.
type Param struct {
	Name       string // source-level parameter name
	Wire       string // required key in the request "args" object
	Source     Source
	Lookup     string // lookup key when Source is SourceLookup
	Optional   bool   // descriptor acceptsUndefined
	TypeSymbol string // original codec type symbol
}

// Endpoint describes one remote endpoint.
type Endpoint struct {
	Package          string
	ID               string
	Method           string // "<namespace>/<method>"
	Mode             Mode
	Kind             Kind
	Context          string // context kind when Kind is KindContext
	ContextWire      string // context wire field when Kind is KindContext
	ScopeContext     string
	ScopeWire        string
	Cancellation     string // cancellation parameter name, if any
	Params           []Param
	UplinkTypeSymbol string
	ResultTypeSymbol string
}

`)

	b.WriteString("// Registry maps \"<namespace>/<method>\" to its descriptor. It is what the\n")
	b.WriteString("// RPC client consults for argument validation and transport selection.\n")
	b.WriteString("var Registry = map[string]Endpoint{\n")
	seen := map[string]bool{}
	for _, p := range pkgs {
		for _, e := range p.tf.Descriptors {
			if seen[e.FullName] {
				fmt.Fprintf(&b, "\t// NOTE: duplicate endpoint %q from package %q skipped.\n", e.FullName, p.shortName)
				continue
			}
			seen[e.FullName] = true
			b.WriteString("\t" + strconv.Quote(e.FullName) + ": ")
			val := renderEndpointValue(e, p.shortName, "\t")
			b.WriteString(strings.ReplaceAll(val, "\n", "\n\t"))
			b.WriteString("\n")
		}
	}
	b.WriteString("}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generated registry does not parse: %w\n--- raw output ---\n%s", err, b.String())
	}
	return src, nil
}
