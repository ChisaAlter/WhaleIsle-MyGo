func mustParse(t *testing.T, src string) *parsedFile {
	t.Helper()
	pf, err := parseTypertFile(src)
	if err != nil {
		t.Fatalf("parseTypertFile: %v", err)
	}
	return pf
}

func parseTestData(t *testing.T, pkg string) *parsedFile {
	t.Helper()
	path := filepath.Join("testdata", pkg, "lib", "typert.remote-client.js")
	src, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return mustParse(t, string(src))
}

func TestTokenizeSkipsCommentsStringsAndRegex(t *testing.T) {
	src := "// comment\n/* block */ const a = 'x' + \"/y\" + `tpl ${z}`;\nvar re = /ab[c]x/gi;"
	toks, err := tokenize(src)
	if err != nil {
		t.Fatalf("tokenize: %v", err)
	}
	var idents []string
	for _, tk := range toks {
		if tk.kind == tkIdent {
			idents = append(idents, tk.val)
		}
	}
	// The regex and string literals must not leak identifier tokens.
	want := []string{"const", "a", "var", "re"}
	if len(idents) != len(want) {
		t.Fatalf("idents = %v, want %v", idents, want)
	}
	for i := range want {
		if idents[i] != want[i] {
			t.Fatalf("idents = %v, want %v", idents, want)
		}
	}
}

func TestParseDshLLMFile(t *testing.T) {
	pf := parseTestData(t, "dsh-llm")
	if got := pf.file.Package; got != "@deepseek-ai/dsh-llm" {
		t.Fatalf("package = %q", got)
	}
	if len(pf.file.Descriptors) != 3 {
		t.Fatalf("descriptors = %d, want 3", len(pf.file.Descriptors))
	}
	e := pf.file.Descriptors[0]
	if e.FullName != "llm/discoverModels" || e.Stream || e.Kind != "direct" {
		t.Fatalf("unexpected first descriptor: %+v", e)
	}
	if len(e.Params) != 2 {
		t.Fatalf("params = %d, want 2", len(e.Params))
	}
	p0 := e.Params[0]
	if p0.Wire != "settingsNs" || p0.Source != "json" || p0.Lookup != "" {
		t.Fatalf("param 0 = %+v", p0)
	}
	if p0.TypeSymbol != "@deepseek-ai/dsh-llm#llm/discoverModels:settingsNs" {
		t.Fatalf("param 0 typeSymbol = %q", p0.TypeSymbol)
	}
	s0 := pf.schemas[p0.SchemaRef]
	if s0 == nil || s0.Kind != "string" {
		t.Fatalf("param 0 schema = %+v", s0)
	}
	p1 := e.Params[1]
	s1 := pf.schemas[p1.SchemaRef]
	if s1 == nil || s1.Kind != "object" || len(s1.Fields) != 4 {
		t.Fatalf("param 1 schema = %+v", s1)
	}
	if s1.Fields[0].Name != "provider" || s1.Fields[0].Schema.Kind != "string" || !s1.Fields[0].Schema.Optional {
		t.Fatalf("param 1 field 0 = %+v", s1.Fields[0])
	}
	res := pf.schemas[e.ResultSchemaRef]
	if res == nil || res.Kind != "array" || res.Elem == nil || res.Elem.Kind != "object" {
		t.Fatalf("result schema = %+v", res)
	}
	if e.ResultTypeSymbol != "@deepseek-ai/dsh-llm#llm/discoverModels:result" {
		t.Fatalf("result typeSymbol = %q", e.ResultTypeSymbol)
	}
}

func TestParseDshGoalFile(t *testing.T) {
	pf := parseTestData(t, "dsh-goal")
	if got := pf.file.Package; got != "@deepseek-ai/dsh-goal" {
		t.Fatalf("package = %q", got)
	}
	if len(pf.file.Descriptors) != 6 {
		t.Fatalf("descriptors = %d, want 6", len(pf.file.Descriptors))
	}
	var clear *endpointDesc
	for _, e := range pf.file.Descriptors {
		if e.FullName == "goals/clear" {
			clear = e
		}
	}
	if clear == nil {
		t.Fatalf("goals/clear not found")
	}
	if clear.ScopeContext != "agent" || clear.ScopeWire != "agentId" {
		t.Fatalf("scope = %q/%q", clear.ScopeContext, clear.ScopeWire)
	}
	if len(clear.Params) != 2 {
		t.Fatalf("params = %d, want 2", len(clear.Params))
	}
	p0 := clear.Params[0]
	if p0.Wire != "agentId" || p0.Source != "lookup" || p0.Lookup != "agent" {
		t.Fatalf("param 0 = %+v", p0)
	}
	if p0.TypeSymbol != "@deepseek-ai/dsh-session/types#SessionId" {
		t.Fatalf("param 0 typeSymbol = %q", p0.TypeSymbol)
	}
	// branded string schema: z.intersection(z.string(), z.unknown())
	s0 := pf.schemas[p0.SchemaRef]
	if s0 == nil || s0.Kind != "intersection" || len(s0.Members) != 2 {
		t.Fatalf("param 0 schema = %+v", s0)
	}
}

func TestParseStreamAndContextDescriptor(t *testing.T) {
	src := `/* Generated by @deepseek-ai/dsh-typert-generator from the Host FaceModel — do not edit. */
import { z } from 'zod'

const _p0$schema = z.string()
const _u$schema = z.number()

export const TYPERT_REMOTE = {
  package: '@test/stream-pkg',
  descriptors: [
    {
      id: '@test/stream-pkg#terminal/follow',
      service: 'terminal',
      namespace: 'terminal',
      method: 'follow',
      mode: 'stream',
      invocation: { kind: 'context', context: 'session', wire: 'sessionId' },
      cancellation: { parameter: 'signal' },
      uplink: {
        codec: {
          mode: 'strict',
          typeSymbol: '@test/types#UplinkItem',
          schema: _u$schema,
        },
      },
      parameters: [
        {
          name: 'id',
          wire: 'id',
          source: 'json',
          acceptsUndefined: true,
          codec: {
            mode: 'strict',
            typeSymbol: '@test/types#WebTerminalId',
            schema: _p0$schema,
          },
        },
      ],
      result: { mode: 'src-json' },
    },
  ],
}

export default TYPERT_REMOTE
`
	pf := mustParse(t, src)
	if len(pf.file.Descriptors) != 1 {
		t.Fatalf("descriptors = %d, want 1", len(pf.file.Descriptors))
	}
	e := pf.file.Descriptors[0]
	if !e.Stream || e.Kind != "context" || e.Context != "session" || e.ContextWire != "sessionId" {
		t.Fatalf("endpoint = %+v", e)
	}
	if e.Cancellation != "signal" || !e.HasUplink || e.UplinkTypeSymbol != "@test/types#UplinkItem" {
		t.Fatalf("endpoint = %+v", e)
	}
	if e.ResultMode != "src-json" || e.ResultSchemaRef != "" || e.ResultTypeSymbol != "" {
		t.Fatalf("result = mode %q ref %q symbol %q", e.ResultMode, e.ResultSchemaRef, e.ResultTypeSymbol)
	}
	if len(e.Params) != 1 || !e.Params[0].AcceptsUndefined {
		t.Fatalf("params = %+v", e.Params)
	}
	us := pf.schemas[e.UplinkSchemaRef]
	if us == nil || us.Kind != "number" {
		t.Fatalf("uplink schema = %+v", us)
	}
}

func TestParseNestedAndRecursiveValueSchemas(t *testing.T) {
	// Exercises nested objects, records with recursive lazy references and
	// self-referential JsonValue-style unions.
	src := `import { z } from 'zod'
const JsonValue$schema = z.union([z.literal(null), z.string(), z.number(), z.array(z.lazy(() => JsonValue$schema)), z.record(z.string(), z.lazy(() => JsonValue$schema))])
const Outer$schema = z.object({
  'tree': z.record(z.string(), z.lazy(() => Outer$schema)),
  'value': JsonValue$schema,
})

export const TYPERT_REMOTE = {
  package: '@test/recursive',
  descriptors: [],
}
`
	pf := mustParse(t, src)
	outer := pf.schemas["Outer$schema"]
	if outer == nil || outer.Kind != "object" || len(outer.Fields) != 2 {
		t.Fatalf("outer schema = %+v", outer)
	}
	tree := outer.Fields[0]
	if tree.Name != "tree" || tree.Schema.Kind != "record" {
		t.Fatalf("tree field = %+v", tree)
	}
	jv := pf.schemas["JsonValue$schema"]
	if jv == nil || jv.Kind != "union" || len(jv.Members) != 5 {
		t.Fatalf("jsonvalue schema = %+v", jv)
	}
}
