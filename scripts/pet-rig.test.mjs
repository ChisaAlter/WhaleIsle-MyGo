import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import vm from 'node:vm';
const file=new URL('../internal/desktop/pet/assets/pet-rig.js',import.meta.url);
assert.ok(existsSync(file),'packaged native rig renderer must exist');
const scope={window:{},Float32Array,Map,Set,Math,Error};
vm.runInNewContext(readFileSync(file,'utf8'),scope);
const manifest=JSON.parse(readFileSync(new URL('../internal/desktop/pet/assets/rig/manifest.json',import.meta.url)));
const ops=[];
const ctx=new Proxy({globalAlpha:1},{get:(target,key)=>key in target?target[key]:(...args)=>ops.push([key,...args])});
const loads=[];
const rig=await scope.window.WhalePetRig.create({ctx,width:390,height:492,manifest,loadImage:async name=>{loads.push(name);return {naturalWidth:502,naturalHeight:695,name};}});
assert.deepEqual(loads.sort(),['shell.png','tail.png']);
const pose=new Float32Array(45);
rig.frame(0,{pose,state:''});
assert.equal(ops.filter(x=>x[0]==='drawImage').length,2,'tail and actual shell must both draw');
const idle=JSON.stringify(ops);ops.length=0;
rig.frame(1,{pose,state:'eat'});
assert.notEqual(JSON.stringify(ops),idle,'real layer transforms change with state/time');
assert.ok(ops.some(x=>x[0]==='rotate'&&x[1]!==0));
rig.close();ops.length=0;rig.frame(2,{pose,state:'running'});assert.equal(ops.length,0);
await assert.rejects(scope.window.WhalePetRig.create({ctx,manifest,loadImage:async()=>null}),/missing/);
await assert.rejects(scope.window.WhalePetRig.create({ctx,manifest:{...manifest,body:{...manifest.body,file:'https://example.org/a.png'}},loadImage:async()=>null}),/resource/);
console.log('PET09 rig composition, motion, deduplication, resource bounds and close passed');
