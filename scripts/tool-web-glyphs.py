"""Extract installed CC0 site marks and the medium globe into native SVG data."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(r"C:\软件\Whale Isle\resources\vendor\deepseek-harness\apps\web\dist\assets\index-wKUmVWbt.js")
text = SOURCE.read_text(encoding="utf-8")
hosts = re.search(r'const SH=\{([^}]+)\};function IH', text).group(1)
entries = re.findall(r'"([^"]+)":(\w+)', hosts)
marks = {}
for host, symbol in entries:
    if symbol not in marks:
        start = re.search(r'\b' + re.escape(symbol) + r'=\{title:', text).start()
        match = re.search(r'path:("(?:[^"\\]|\\.)*")', text[start:])
        marks[symbol] = json.loads(match.group(1))
globe_paths = [
    'M7.99986 14.0887C11.3626 14.0887 14.0886 11.3627 14.0886 7.99998C14.0886 4.63727 11.3626 1.91125 7.99986 1.91125C4.63715 1.91125 1.91113 4.63727 1.91113 7.99998C1.91113 11.3627 4.63715 14.0887 7.99986 14.0887Z',
    'M2.34619 8H13.6538',
    'M7.99976 14.0889C9.23509 14.0889 10.1743 11.3629 10.1743 8.00006C10.1743 4.63739 9.23509 1.91138 7.99976 1.91138',
    'M7.99973 14.0889C6.76445 14.0889 5.8252 11.3629 5.8252 8.00006C5.8252 4.63739 6.76445 1.91138 7.99973 1.91138',
]
assert all(path in text for path in globe_paths)
header = 'package markdown\n\nimport "github.com/egoist/mygo/ui"\n\n'
header += '// Installed simple-icons CC0-1.0 site artwork; generated by scripts/tool-web-glyphs.py.\n'
header += '// Installed web bundle SHA256 ' + hashlib.sha256(SOURCE.read_bytes()).hexdigest() + '.\n'
header += 'var webSiteMarks = map[string]*ui.SVG{\n'
for symbol, artwork in marks.items():
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-2 -2 28 28" fill="none"><path d="' + artwork + '" fill="currentColor"/></svg>'
    header += '\t"' + symbol + '": ui.MustParseSVG([]byte(`' + svg + '`)),\n'
header += '}\n\nvar webSiteHosts = map[string]string{\n'
for host, symbol in entries:
    header += '\t"' + host + '": "' + symbol + '",\n'
header += '}\n\n'
svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" fill="none" stroke-width="1.3">' + ''.join('<path d="' + path + '" stroke="currentColor"/>' for path in globe_paths) + '</svg>'
header += 'var webGlobe = ui.MustParseSVG([]byte(`' + svg + '`))\n'
output = ROOT / 'internal/ui/widgets/markdown/tool_web_glyph_data.go'
output.write_text(header, encoding='utf-8')
print(f'Installed web glyphs: {len(entries)} host suffixes / {len(marks)} site marks and one medium globe')
